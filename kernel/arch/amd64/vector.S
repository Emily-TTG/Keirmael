#include <kml/kernel/arch/amd64/interrupt.h>

.extern kml_kernel_arch_amd64_interrupt_service_routine

.macro kml_kernel_arch_amd64_push_all
	pushq %rax
	pushq %rbx
	pushq %rcx
	pushq %rdx

	pushq %rsi
	pushq %rdi

	pushq %r8
	pushq %r9
	pushq %r10
	pushq %r11
	pushq %r12
	pushq %r13
	pushq %r14
	pushq %r15

	pushq %rbp
.endm

.macro kml_kernel_arch_amd64_pop_all
	popq %rbp

	popq %r15
	popq %r14
	popq %r13
	popq %r12
	popq %r11
	popq %r10
	popq %r9
	popq %r8

	popq %rdi
	popq %rsi

	popq %rdx
	popq %rcx
	popq %rbx
	popq %rax
.endm

.macro kml_kernel_arch_amd64_interrupt_handler_error_code vector
	.align KML_KERNEL_ARCH_AMD64_INTERRUPT_HANDLER_STRIDE
	.global kml_kernel_arch_amd64_interrupt_handler_\vector
	kml_kernel_arch_amd64_interrupt_handler_\vector:
		cld
		movq $\vector, %rdi
		movq %rsp, %rsi
		kml_kernel_arch_amd64_push_all
		callq kml_kernel_arch_amd64_interrupt_service_routine
		kml_kernel_arch_amd64_pop_all
		addq $0x8, %rsp
		iretq
.endm

.macro kml_kernel_arch_amd64_interrupt_handler vector
	.align KML_KERNEL_ARCH_AMD64_INTERRUPT_HANDLER_STRIDE
	.global kml_kernel_arch_amd64_interrupt_handler_\vector
	kml_kernel_arch_amd64_interrupt_handler_\vector:
		cld
		pushq 0
		movq $\vector, %rdi
		movq %rsp, %rsi
		kml_kernel_arch_amd64_push_all
		callq kml_kernel_arch_amd64_interrupt_service_routine
		kml_kernel_arch_amd64_pop_all
		addq $0x8, %rsp
		iretq
.endm

